// Rolls the declarations project plugins type-check against into
// crates/ludenea-project/types/, which `Project::write_game_types` copies into a project's
// `.ludenea/types/`. Each module becomes one ambient `declare module`, so the generated
// `game.d.ts` (another `declare module "@ludenea/editor-shell"`) merges into `ComponentTypes`.
// Development only; the output is committed. Run with `node editor/scripts/bundle-dts.mjs`.
import { execFileSync } from "node:child_process";
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { rollup } from "rollup";
import { dts } from "rollup-plugin-dts";

const editor = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(editor, "../crates/ludenea-project/types");
const shell = join(editor, "packages/editor-shell");
const reactTypes = realpathSync(join(shell, "node_modules/@types/react"));
const HEADER = "// Generated by editor/scripts/bundle-dts.mjs from the editor packages; do not edit.\n";

// csstype's documentation is most of its size and none of what plugins need.
const stripCsstypeDocs = {
  name: "strip-csstype-docs",
  transform: (code, id) => (id.includes("/csstype/") ? code.replace(/\/\*\*[\s\S]*?\*\/\n?/g, "") : null),
};

async function roll(input, { external = [], respectExternal = false } = {}) {
  const bundle = await rollup({ input, external, plugins: [stripCsstypeDocs, dts({ respectExternal })] });
  const { output } = await bundle.generate({ format: "es" });
  await bundle.close();
  return output[0].code;
}

/** `code` as the body of `declare module "name"`: top-level `declare` is implied there. */
function ambient(name, code) {
  const body = code
    .replace(/^export declare /gm, "export ")
    .replace(/^declare (?!global\b)/gm, "")
    .trimEnd();
  return `declare module "${name}" {\n${body}\n}\n`;
}

execFileSync(join(editor, "node_modules/.bin/tsc"), ["-b"], { cwd: editor, stdio: "inherit" });

const shared = ["@ludenea/control-client", "react", "react/jsx-runtime"];
const editorShell = await roll(join(shell, "dist/src/index.d.ts"), { external: shared, respectExternal: true });
const controlClient = await roll(join(editor, "packages/control-client/dist/src/index.d.ts"));

// @types/react is a UMD namespace with `export =`; rollup turns that into a default export.
const reactIndex = (await roll(join(reactTypes, "index.d.ts"), { respectExternal: true }))
  .replace(/^\/\/\/ <reference path="global\.d\.ts" \/>\n/m, "")
  .replace(/^export \{ React as default \};$/m, "export = React;");
const jsxRuntime = readFileSync(join(reactTypes, "jsx-runtime.d.ts"), "utf8").replaceAll('"./"', '"react"');
const reactGlobals = readFileSync(join(reactTypes, "global.d.ts"), "utf8");

const files = {
  "control-client.d.ts": ambient("@ludenea/control-client", controlClient),
  "editor-shell.d.ts": ambient("@ludenea/editor-shell", editorShell),
  "react.d.ts": [reactGlobals.trimEnd() + "\n", ambient("react", reactIndex), ambient("react/jsx-runtime", jsxRuntime)].join("\n"),
};
for (const name of Object.keys(files).sort()) {
  writeFileSync(join(out, name), HEADER + files[name]);
  console.log(`wrote ${name} (${files[name].length} bytes)`);
}
