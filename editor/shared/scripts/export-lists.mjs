// Writes the entries of the shared modules build (src/*.js): each re-exports an explicit list
// of names, so the ES modules the import map points at export what plugins import. React is
// CommonJS, where `export *` would export nothing; the editor packages' lists come from their
// TypeScript sources (value exports only). Run by `pnpm build` in this directory.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const shared = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(shared, "package.json"));
const ts = require("@typescript/typescript6");
const HEADER = "// Generated by scripts/export-lists.mjs; do not edit.\n";

/** The value (not type-only) exports of a TypeScript module. */
function valueExports(file) {
  const program = ts.createProgram([file], { allowImportingTsExtensions: true, noEmit: true, jsx: ts.JsxEmit.ReactJSX, skipLibCheck: true });
  const checker = program.getTypeChecker();
  const module = checker.getSymbolAtLocation(program.getSourceFile(file));
  return checker
    .getExportsOfModule(module)
    .filter((symbol) => {
      // `export { type Registry }` names a class, but only its type reaches importers.
      const typeOnly = symbol.declarations?.some((declaration) => ts.isExportSpecifier(declaration) && (declaration.isTypeOnly || declaration.parent.parent.isTypeOnly));
      if (typeOnly) return false;
      const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
      return target.flags & ts.SymbolFlags.Value;
    })
    .map((symbol) => symbol.name)
    .sort();
}

/** An entry bundling the CommonJS module at `path`, `names` destructured from its exports. */
const commonJs = (path, names, extra = "") =>
  `${HEADER}import module from "${path}";\n${extra}\nexport const { ${names.join(", ")} } = module;\nexport default module;\n`;

const reexport = (path, names) => `${HEADER}export { ${names.join(", ")} } from "${path}";\n`;

const react = Object.keys(require("react")).sort();
const jsxRuntime = Object.keys(require("react/jsx-runtime")).sort();
const reactDom = Object.keys(require("react-dom")).sort();
// Read by the end-to-end smoke test: one React may exist however many plugins load. It ships in
// production on purpose: one global counter costs nothing, and the test then checks the build
// users run rather than a variant with a flag set.
const probe = "globalThis.__ludeneaReactInstances = (globalThis.__ludeneaReactInstances ?? 0) + 1;\n";
const packages = join(shared, "../packages");

writeFileSync(join(shared, "src/react.js"), commonJs("../node_modules/react/index.js", react, probe));
writeFileSync(join(shared, "src/react-jsx-runtime.js"), commonJs("../node_modules/react/jsx-runtime.js", jsxRuntime));
writeFileSync(join(shared, "src/react-dom.js"), commonJs("../node_modules/react-dom/index.js", reactDom));
for (const [name, source] of [
  ["editor-shell", "editor-shell/src/index.ts"],
  ["editor-shell-app", "editor-shell/src/app.ts"],
  ["control-client", "control-client/src/index.ts"],
]) {
  writeFileSync(join(shared, `src/${name}.js`), reexport(`../../packages/${source}`, valueExports(join(packages, source))));
}
